"""Settings, read once from environment variables."""

import os
from dataclasses import dataclass

# 127.0.0.1 rather than localhost: on Windows "localhost" tries IPv6 first and stalls.
LOCAL_DATABASE_URL = "postgresql://remixfox:remixfox@127.0.0.1:5433/remixfox"


def _database_url(raw: str) -> str:
    """Point SQLAlchemy at the psycopg 3 driver.

    Render (and most hosts) hand out plain postgres:// or postgresql:// URLs.
    """
    for prefix in ("postgres://", "postgresql://"):
        if raw.startswith(prefix):
            return "postgresql+psycopg://" + raw[len(prefix):]
    return raw


def _flag(name: str, default: str = "true") -> bool:
    return os.getenv(name, default).strip().lower() not in ("0", "false", "no", "off")


def _int(name: str, default: int) -> int:
    try:
        return int(os.getenv(name, default))
    except ValueError:
        return default


@dataclass(frozen=True)
class Settings:
    database_url: str
    # Apify (https://apify.com) fetches reels from Instagram. Without a token the
    # app still works, but fetch jobs fail with a clear "not connected" message.
    apify_token: str
    apify_actor_id: str
    reels_per_competitor: int
    # Fetch jobs also get transcripts for reels that have none (paid per minute).
    auto_transcribe: bool
    # Keys the sign-in code hashes and the Telegram webhook secret. Generated by Render.
    secret_key: str
    # Registering with this e-mail makes the account the owner (no subscription
    # needed, manages the AI and admins, gets the data from before accounts existed).
    owner_email: str
    # Stripe subscriptions (plans and prices come from app/plans.py); without a key,
    # the payment page says payments are not set up.
    stripe_secret_key: str
    stripe_webhook_secret: str
    # The AI step (GPT-5.6 Luna through the OpenAI API, app/ai.py).
    openai_api_key: str
    ai_worker: bool  # the AI worker thread (off in tests)
    # Sign-in codes by e-mail, sent with Resend (https://resend.com) from a
    # verified domain. Without a key the code is written to the server log.
    resend_api_key: str
    mail_from: str
    # The Telegram bot that signs people in (from @BotFather).
    telegram_bot_token: str
    # The site's own address (https://remixfox.co.uk). When set, pages opened at
    # the onrender.com address move there; empty until the domain is verified.
    public_url: str


settings = Settings(
    database_url=_database_url(os.getenv("DATABASE_URL") or LOCAL_DATABASE_URL),
    apify_token=os.getenv("APIFY_TOKEN", "").strip(),
    apify_actor_id=os.getenv("APIFY_ACTOR_ID", "apify~instagram-reel-scraper").strip(),
    reels_per_competitor=max(1, min(_int("REELS_PER_COMPETITOR", 20), 100)),
    auto_transcribe=_flag("AUTO_TRANSCRIBE"),
    secret_key=os.getenv("SECRET_KEY", "").strip() or "local-development-only-secret",
    owner_email=os.getenv("OWNER_EMAIL", "").strip().lower(),
    stripe_secret_key=os.getenv("STRIPE_SECRET_KEY", "").strip(),
    stripe_webhook_secret=os.getenv("STRIPE_WEBHOOK_SECRET", "").strip(),
    openai_api_key=os.getenv("OPENAI_API_KEY", "").strip(),
    ai_worker=_flag("AI_WORKER"),
    resend_api_key=os.getenv("RESEND_API_KEY", "").strip(),
    mail_from=os.getenv("MAIL_FROM", "").strip() or "Remixfox <login@remixfox.co.uk>",
    telegram_bot_token=os.getenv("TELEGRAM_BOT_TOKEN", "").strip(),
    public_url=os.getenv("PUBLIC_URL", "").strip().rstrip("/"),
)
